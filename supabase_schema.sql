    mcu_ulang = (mcu_awal + INTERVAL '9 months')::DATE,
    docs = jsonb_set(
        COALESCE(docs, '{}'::JSONB),
        '{MCU}',
        to_jsonb(to_char((mcu_awal + INTERVAL '9 months')::DATE, 'YYYY-MM-DD')),
        true
    )
WHERE mcu_awal IS NOT NULL
  AND (
      mcu_ulang IS NULL
      OR mcu_ulang = (mcu_awal + INTERVAL '12 months')::DATE
      OR COALESCE(docs->>'MCU', '') = ''
      OR docs->>'MCU' = to_char((mcu_awal + INTERVAL '12 months')::DATE, 'YYYY-MM-DD')
  );


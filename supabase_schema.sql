-- ============================================================================
-- TRIGGER AUTO UPDATE `updated_at`
-- ============================================================================

DO $$
DECLARE
    tbl TEXT;
    tables_with_updated_at TEXT[] := ARRAY[
        'master_jabatan', 'master_perusahaan', 'master_kode_roster', 'master_kode_spi',
        'manpower', 'komisioning_unit', 'roster_bulanan', 'roster_pic', 'roster_daily_log',
        'absensi_harian', 'atr_weekly', 'atr_monthly', 'atr_punishment_history',
        'kpi_pengawas', 'hm_ua_daily', 'ua_weekly_upload', 'ua_mtd_upload',
        'rental_bib', 'big_crane_timeframe', 'operasional_lt_wt', 'operasional_lifting',
        'pusat_informasi'
    ];
BEGIN
    FOREACH tbl IN ARRAY tables_with_updated_at LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON public.%I;', tbl, tbl);
        EXECUTE format(
            'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();',
            tbl, tbl
        );
    END LOOP;
END $$;


-- ============================================================================
-- PANTAU SE — SKEMA DATABASE SUPABASE (PostgreSQL)
-- Seluruh tabel disesuaikan 100% dengan struktur data & modul aplikasi web:
--   1. Master Data (Jabatan, Perusahaan, Kode Roster, Kode SPI)
--   2. Data Manpower (termasuk Password Login, Bapak Asuh, MCU 9 Bulan, Dokumen Legalitas)
--   3. Komisioning Unit & Master Unit (HM Rate, Rental Rate)
--   4. Roster SE (Roster Bulanan, PIC per Roster, & Log Roster Daily)
--   5. Performa Manpower (Absensi Harian, ATR Weekly, ATR Monthly, Punishment)
--   6. KPI Pengawas (Weekly MTD / Closed)
--   7. Utilitas & Operasi Unit (HM Daily, UA Daily/Weekly/MTD, Rental BIB, Big Crane)
--   8. Operasional SE (Lubetruck/Watertruck 23 Kolom & Lifting 28 Kolom)
--   9. Beranda / Pusat Informasi & Ruang Obrolan (Komentar)
--  10. Media Registry (Sinkron Kode Link Google Drive <-> Spreadsheet GAS)
--
-- CATATAN:
--   - Total 24 tabel; seluruh tabel memiliki ROW LEVEL SECURITY (RLS) DISABLED sesuai kebutuhan.
--   - Aman dijalankan ulang (Idempotent: CREATE TABLE IF NOT EXISTS & ALTER TABLE ADD COLUMN IF NOT EXISTS).
-- ============================================================================

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;


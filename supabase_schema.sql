-- ============================================================================
-- 12. PROTEKSI LEVEL DATABASE: ZERO FOTO / BASE64 MASUK SUPABASE
-- Semua foto wajib ke Google Drive via GAS & link disimpan di Spreadsheet.
-- Constraint memakai NOT VALID agar aman pada database eksisting namun
-- MEMBLOKIR 100% semua INSERT/UPDATE baru yang mencoba memasukkan data:/blob:/base64.
-- ============================================================================

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_punishment_no_base64_photo') THEN
        ALTER TABLE public.atr_punishment_history
            ADD CONSTRAINT chk_punishment_no_base64_photo
            CHECK (eviden_photo_url NOT ILIKE 'data:%' AND eviden_photo_url NOT ILIKE 'blob:%') NOT VALID;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_info_komentar_no_base64_media') THEN
        ALTER TABLE public.pusat_informasi_komentar
            ADD CONSTRAINT chk_info_komentar_no_base64_media
            CHECK (media_url NOT ILIKE 'data:%' AND media_url NOT ILIKE 'blob:%') NOT VALID;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_media_registry_no_base64') THEN
        ALTER TABLE public.media_registry
            ADD CONSTRAINT chk_media_registry_no_base64
            CHECK (
                view_url NOT ILIKE 'data:%' AND view_url NOT ILIKE 'blob:%' AND
                drive_url NOT ILIKE 'data:%' AND drive_url NOT ILIKE 'blob:%' AND
                thumbnail_url NOT ILIKE 'data:%' AND thumbnail_url NOT ILIKE 'blob:%'
            ) NOT VALID;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_manpower_no_base64_media_links') THEN
        ALTER TABLE public.manpower
            ADD CONSTRAINT chk_manpower_no_base64_media_links
            CHECK (media_links::text NOT ILIKE '%data:image/%' AND media_links::text NOT ILIKE '%;base64,%') NOT VALID;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_komisioning_no_base64_media_links') THEN
        ALTER TABLE public.komisioning_unit
            ADD CONSTRAINT chk_komisioning_no_base64_media_links
            CHECK (media_links::text NOT ILIKE '%data:image/%' AND media_links::text NOT ILIKE '%;base64,%') NOT VALID;
    END IF;
END $$;

-- ============================================================================
-- 13. AKTIVASI SUPABASE REALTIME PUBLICATION (PRIORITAS BERANDA & DATA AKTIF)
-- Aman dijalankan ulang (Idempotent) — membuat semua perangkat menerima
-- perubahan INSERT / UPDATE / DELETE secara real-time via 1 koneksi WebSocket.
-- ============================================================================

DO $$
DECLARE
    tbl TEXT;
    realtime_tables TEXT[] := ARRAY[
        'pusat_informasi',
        'pusat_informasi_komentar',
        'roster_bulanan',
        'roster_pic',
        'manpower',
        'komisioning_unit',
        'atr_punishment_history',
        'operasional_lt_wt',
        'operasional_lifting',
        'rental_bib',
        'big_crane_timeframe'
    ];
BEGIN
    FOREACH tbl IN ARRAY realtime_tables LOOP
        EXECUTE format('ALTER TABLE public.%I REPLICA IDENTITY FULL;', tbl);
        IF NOT EXISTS (
            SELECT 1
            FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime'
              AND schemaname = 'public'
              AND tablename = tbl
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;', tbl);
        END IF;
    END LOOP;
END $$;
